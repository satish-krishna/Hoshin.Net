using System.Text.RegularExpressions;
using Hoshin.Workflow.Common;
using Hoshin.Workflow.Git;

namespace Hoshin.Workflow.Workspace;

public sealed record MarkerLine(int Line, string Text);

public sealed record InstructionsInput(
    string Workspace,
    string Master,
    string MasterName,
    Marker Marker,
    bool Write,
    bool AllowHome);

public sealed record InstructionsResult(
    string WorkspaceMd,
    string ClaudeMd,
    List<MarkerLine> MarkerLines,
    List<string> Problems);

/// <summary>Generates <c>intent/workspace.md</c> and maintains the hoshin block in <c>CLAUDE.md</c>.</summary>
public static class InstructionsService
{
    public const string StartMarker = "<!-- hoshin:start -->";
    public const string EndMarker = "<!-- hoshin:end -->";

    private const string ExampleRow = "| <system> | <repo>, <repo> | `<master>/intent/<system>/context/` | `<master>/intent/<system>/policies.md` |";
    private const string ExampleAppRow = "| <app> | `<folder>` | `intent/<system>/context/<app>.md` | `<check>` |";
    private const string Rerun = "run the hoshin setup skill with `--instructions`";
    private const string NoInstructions = $"This workspace has no workspace instructions yet; {Rerun}.";
    private const string OutOfDate = $"The workspace instructions on this machine are missing or out of date; {Rerun}.";

    private static readonly Regex LineChunkRegex = new(@"[^\n]*\n|[^\n]+$", RegexOptions.Compiled);

    public static string ReadTemplate(WorkspaceLayout layout)
    {
        var name = layout == WorkspaceLayout.SingleRepo ? "workspace-single-repo.md" : "workspace.md";
        var resource = $"Hoshin.Workflow.Workspace.Templates.{name}";
        using var stream = typeof(InstructionsService).Assembly.GetManifestResourceStream(resource)
            ?? throw new CouldNotRunException($"cannot read the workspace template {name}");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }

    public static string WorkspaceText(string template, string masterName, Marker marker)
    {
        var systems = marker.Systems.ToList();
        if (systems.Count == 0)
        {
            throw new CouldNotRunException("the marker lists no system");
        }

        if (marker.Layout == WorkspaceLayout.SingleRepo)
        {
            return SingleRepoText(template, systems[0]);
        }

        var lines = template.Replace("\r\n", "\n").Replace("\r", "\n").TrimEnd('\n').Split('\n').ToList();
        var at = lines.IndexOf(ExampleRow);
        if (at < 0)
        {
            throw new CouldNotRunException("workspace.md template has no example row for the systems table");
        }

        var filled = lines.Select(l => l.Replace("<master>", masterName, StringComparison.Ordinal)).ToList();
        var rows = systems.Select(kv =>
        {
            var list = kv.Value.Repos.Count > 0 ? string.Join(", ", kv.Value.Repos) : $"all repositories except {masterName}";
            return $"| {kv.Key} | {list} | `{masterName}/intent/{kv.Key}/context/` | `{masterName}/intent/{kv.Key}/policies.md` |";
        }).ToList();
        filled.RemoveAt(at);
        filled.InsertRange(at, rows);
        return string.Join('\n', filled) + "\n";
    }

    private static string SingleRepoText(string template, KeyValuePair<string, MarkerSystem> sys)
    {
        var lines = template.Replace("\r\n", "\n").Replace("\r", "\n").TrimEnd('\n').Split('\n').ToList();
        var at = lines.IndexOf(ExampleAppRow);
        if (at < 0)
        {
            throw new CouldNotRunException("workspace-single-repo.md template has no example row for the apps table");
        }

        var rows = sys.Value.Apps.Select(kv =>
        {
            var check = $"git rev-list --count <source_commit>..HEAD -- {kv.Value} \":(exclude)intent\" \":(exclude).hoshin.json\"";
            return $"| {kv.Key} | `{kv.Value}` | `intent/{sys.Key}/context/{kv.Key}.md` | `{check}` |";
        }).ToList();
        lines.RemoveAt(at);
        lines.InsertRange(at, rows);
        return string.Join('\n', lines).Replace("<system>", sys.Key, StringComparison.Ordinal) + "\n";
    }

    public static string GeneratedLine(string masterName, bool single = false) =>
        $"<!-- generated by hoshin setup from {(single ? "" : $"{masterName}/")}intent/workspace.md; edit outside this block -->";

    public static List<MarkerLine> FindMarkerLines(string text)
    {
        var result = new List<MarkerLine>();
        var lines = LinesOf(text);
        for (var i = 0; i < lines.Count; i++)
        {
            var bare = Bare(lines[i]);
            var trimmed = bare.Trim();
            if (trimmed is StartMarker or EndMarker)
            {
                result.Add(new MarkerLine(i + 1, bare));
            }
        }

        return result;
    }

    public static InstructionsResult Run(InstructionsInput input)
    {
        var single = input.Marker.Layout == WorkspaceLayout.SingleRepo;
        var generated = WorkspaceText(ReadTemplate(input.Marker.Layout), input.MasterName, input.Marker);
        var mdFile = Path.Combine(input.Master, "intent", "workspace.md");
        var claudeFile = Path.Combine(single ? input.Master : input.Workspace, "CLAUDE.md");
        var md = ReadOrNull(mdFile);
        var claude = ReadOrNull(claudeFile);
        var found = claude is null ? [] : FindMarkerLines(claude);
        var home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        var envHome = Environment.GetEnvironmentVariable("HOME");
        var effectiveHome = !string.IsNullOrEmpty(envHome) ? envHome : home;
        var atHome = !single && !string.IsNullOrEmpty(effectiveHome) && PathHelpers.PathsEqual(input.Workspace, effectiveHome) && !input.AllowHome;
        var (blockKind, startIdx, endIdx) = claude is null ? ("none", -1, -1) : BlockAt(claude);
        var problems = new List<string>();

        if (!input.Write)
        {
            var workspaceMd = md is null ? "missing" : md == generated ? "current" : "stale";
            if (workspaceMd == "missing")
            {
                problems.Add(NoInstructions);
            }

            if (workspaceMd == "stale")
            {
                problems.Add($"{mdFile} is out of date with .hoshin.json; {Rerun}.");
            }

            string claudeMd;
            if (atHome)
            {
                claudeMd = "home-folder";
            }
            else if (md is null || blockKind == "none")
            {
                claudeMd = "missing";
            }
            else if (blockKind == "bad")
            {
                claudeMd = "bad-markers";
            }
            else
            {
                claudeMd = Normalize(BlockContent(claude!, startIdx, endIdx)) == Normalize(md) ? "current" : "stale";
            }

            if (claudeMd == "bad-markers")
            {
                problems.Add(BadMarkersMessage(claudeFile, found, wrote: false));
            }
            else if ((claudeMd is "missing" or "stale") && md is not null)
            {
                problems.Add(OutOfDate);
            }

            return new InstructionsResult(workspaceMd, claudeMd, found, problems);
        }

        var wsState = "current";
        if (md != generated)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(mdFile)!);
            File.WriteAllText(mdFile, generated);
            wsState = "written";
        }

        string clState;
        if (atHome)
        {
            clState = "home-folder";
            problems.Add($"The workspace folder {input.Workspace} is the home folder, where a CLAUDE.md applies to every project under it, so {claudeFile} was left untouched. Ask the engineer, and with their agreement rerun with `--allow-home`.");
        }
        else if (blockKind == "bad")
        {
            clState = "bad-markers";
            problems.Add(BadMarkersMessage(claudeFile, found, wrote: true));
        }
        else
        {
            var next = WithBlock(claude, GeneratedLine(input.MasterName, single), generated);
            if (next == claude)
            {
                clState = "current";
            }
            else
            {
                File.WriteAllText(claudeFile, next);
                clState = claude is null ? "created" : "updated";
            }
        }

        var finalMarkers = claude is null || clState is "current" or "bad-markers"
            ? found
            : FindMarkerLines(File.ReadAllText(claudeFile));
        return new InstructionsResult(wsState, clState, finalMarkers, problems);
    }

    private static List<string> LinesOf(string text) =>
        LineChunkRegex.Matches(text).Select(m => m.Value).ToList();

    private static string Bare(string line)
    {
        if (line.EndsWith("\r\n", StringComparison.Ordinal))
        {
            return line[..^2];
        }

        return line.EndsWith('\n') ? line[..^1] : line;
    }

    private static (string Kind, int Start, int End) BlockAt(string text)
    {
        var found = FindMarkerLines(text);
        if (found.Count == 0)
        {
            return ("none", -1, -1);
        }

        var starts = found.Where(m => m.Text.Trim() == StartMarker).ToList();
        var ends = found.Where(m => m.Text.Trim() == EndMarker).ToList();
        if (starts.Count != 1 || ends.Count != 1 || starts[0].Line > ends[0].Line)
        {
            return ("bad", -1, -1);
        }

        return ("ok", starts[0].Line - 1, ends[0].Line - 1);
    }

    private static string Normalize(string text) =>
        string.Join('\n', text.Replace("\r\n", "\n").Replace("\r", "\n").Split('\n').Select(l => l.TrimEnd())).Trim('\n');

    private static string BlockContent(string text, int start, int end)
    {
        var lines = LinesOf(text);
        var inner = lines.Skip(start + 1).Take(end - start - 1).ToList();
        if (inner.Count > 0 && Bare(inner[0]).Trim().StartsWith("<!-- generated by hoshin setup", StringComparison.Ordinal))
        {
            inner.RemoveAt(0);
        }

        return string.Concat(inner);
    }

    private static string WithBlock(string? existing, string generatedComment, string workspaceMd)
    {
        var inner = $"{generatedComment}\n{workspaceMd}";
        if (string.IsNullOrEmpty(existing))
        {
            return $"{StartMarker}\n{inner}{EndMarker}\n";
        }

        var (kind, start, end) = BlockAt(existing);
        if (kind == "none")
        {
            var ended = existing.EndsWith('\n') ? existing : existing + "\n";
            return $"{ended}\n{StartMarker}\n{inner}{EndMarker}\n";
        }

        if (kind == "bad")
        {
            throw new InvalidOperationException("bad markers must be refused before writing");
        }

        var lines = LinesOf(existing);
        var crlf = lines[start].EndsWith("\r\n", StringComparison.Ordinal);
        var body = crlf ? inner.Replace("\n", "\r\n", StringComparison.Ordinal) : inner;
        return string.Concat(lines.Take(start + 1)) + body + string.Concat(lines.Skip(end));
    }

    private static string? ReadOrNull(string path) => File.Exists(path) ? File.ReadAllText(path) : null;

    private static string BadMarkersMessage(string file, List<MarkerLine> lines, bool wrote)
    {
        var shown = string.Join(", ", lines.Select(m => $"line {m.Line}: `{m.Text}`"));
        return $"{file} must hold each of `{StartMarker}` and `{EndMarker}` on its own line exactly once, start first, but the marker lines are {shown}{(wrote ? ", so it was left untouched" : "")}. Fix them and {Rerun}.";
    }
}
