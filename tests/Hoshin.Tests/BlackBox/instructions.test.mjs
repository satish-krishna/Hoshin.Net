// The workspace instructions: `instructions --json [--write]` generates `<master>/intent/workspace.md` from the
// marker and the template, and keeps the block between the hoshin markers in `<workspace>/CLAUDE.md` a copy of it.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { git, repoRoot, run, workspace, write } from './helpers/workspace.mjs';

// With LF line endings, as the program reads it: a checkout with core.autocrlf gives the file CRLF.
const TEMPLATE = readFileSync(join(repoRoot, 'src', 'Hoshin.Workflow', 'Workspace', 'Templates', 'workspace.md'), 'utf8').replace(/\r\n?/g, '\n');
const EXAMPLE_ROW = '| <system> | <repo>, <repo> | `<master>/intent/<system>/context/` | `<master>/intent/<system>/policies.md` |';
const START = '<!-- hoshin:start -->';
const END = '<!-- hoshin:end -->';

const row = (master, system, repos) => `| ${system} | ${repos} | \`${master}/intent/${system}/context/\` | \`${master}/intent/${system}/policies.md\` |`;
const expected = (master, rows) => TEMPLATE.replace(EXAMPLE_ROW, rows.join('\n')).replaceAll('<master>', master);
const generatedLine = (master) => `<!-- generated by hoshin setup from ${master}/intent/workspace.md; edit outside this block -->`;
const block = (master, text) => `${START}\n${generatedLine(master)}\n${text}${END}\n`;

const instructions = (cwd, more = [], env = {}) => run(cwd, ['instructions', '--json', ...more], env);
const read = (path) => readFileSync(path, 'utf8');

test('the template has the example row and the placeholders the command fills', () => {
  assert.ok(TEMPLATE.includes(`\n${EXAMPLE_ROW}\n`));
  assert.ok(TEMPLATE.includes('<master>'));
});

test('one system: every <master> filled, one row, the rest of the template as it is', () => {
  const { ws, master } = workspace();
  const hub = join(ws, 'hub');
  renameSync(master, hub);
  const r = instructions(hub, ['--write']);
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.deepEqual(r.json, { workspaceMd: 'written', claudeMd: 'created', markerLines: [], problems: [] });
  const text = read(join(hub, 'intent', 'workspace.md'));
  assert.equal(text, expected('hub', [row('hub', 'demo', 'app')]));
  assert.match(text, /^\| demo \| app \| `hub\/intent\/demo\/context\/` \| `hub\/intent\/demo\/policies\.md` \|$/m);
  assert.doesNotMatch(text, /<master>|\r/);
  assert.match(text, /<system>.*<repo>|<repo>.*<system>/s, 'placeholders in the prose were filled');
  assert.match(text, /<change>/);
  assert.match(text, /<source_commit>/);
  assert.match(text, /T<n>/);
  assert.ok(text.endsWith('.\n') && !text.endsWith('\n\n'));
  assert.equal(read(join(ws, 'CLAUDE.md')), block('hub', text));
  assert.equal(git(hub, 'status', '--porcelain'), '?? intent/workspace.md', 'it committed something');
});

test('several systems, in marker order; a system with no repositories names every repository but the master', () => {
  const systems = { zeta: { repos: ['web', 'app'] }, alpha: { repos: [] }, mid: {} };
  const { master } = workspace({ marker: { systems }, repos: ['app', 'web'] });
  const r = instructions(master, ['--write']);
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.equal(read(join(master, 'intent', 'workspace.md')), expected('master', [
    row('master', 'zeta', 'web, app'),
    row('master', 'alpha', 'all repositories except master'),
    row('master', 'mid', 'all repositories except master'),
  ]));
});

test('in a change\'s copy, the master is named by the workspace folder of the same repository, not the copy', () => {
  const { ws, master } = workspace();
  const started = run(master, ['change', 'start', '--json', '--system', 'demo', '--change', '2026-11-02-hello', '--type', 'feat', '--scope', 'demo']);
  assert.equal(started.status, 0, started.stdout + started.stderr);
  const copy = join(ws, '.hoshin', 'copies', '2026-11-02-hello');
  const r = instructions(copy, ['--write']);
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const text = read(join(copy, 'intent', 'workspace.md'));
  assert.equal(text, expected('master', [row('master', 'demo', 'app')]));
  assert.ok(read(join(ws, 'CLAUDE.md')).includes(generatedLine('master')));
  assert.equal(existsSync(join(master, 'intent', 'workspace.md')), false, 'it wrote in the engineer\'s checkout');
});

test('a CLAUDE.md with neither marker gets a blank line and the block at the end', () => {
  const { ws, master } = workspace();
  const notes = '# My notes\n\nKeep this line exactly as it is.\n';
  write(join(ws, 'CLAUDE.md'), notes);
  const r = instructions(master, ['--write']);
  assert.equal(r.json.claudeMd, 'updated');
  const text = read(join(master, 'intent', 'workspace.md'));
  assert.equal(read(join(ws, 'CLAUDE.md')), `${notes}\n${block('master', text)}`);
  // the eval graders of setup-writes-workspace-instructions
  const claude = read(join(ws, 'CLAUDE.md'));
  assert.match(claude, /<!-- hoshin:start -->\r?\n<!-- generated by hoshin setup from master\/intent\/workspace\.md[^\n]*\r?\n# hoshin workspace[\s\S]*^\|\s*demo\s*\|\s*app\s*\|[\s\S]*<!-- hoshin:end -->/m);
  assert.match(claude, /^# My notes\r?\n\r?\nKeep this line exactly as it is\./);
  assert.match(text, /^\|\s*demo\s*\|\s*app\s*\|/m);
  assert.doesNotMatch(text, /<master>|\|\s*<system>\s*\||<repo>, <repo>/);
});

test('a CLAUDE.md without a newline at its end, or empty, still gets the block on its own lines', () => {
  const { ws, master } = workspace();
  write(join(ws, 'CLAUDE.md'), 'notes');
  instructions(master, ['--write']);
  const text = read(join(master, 'intent', 'workspace.md'));
  assert.equal(read(join(ws, 'CLAUDE.md')), `notes\n\n${block('master', text)}`);
  write(join(ws, 'CLAUDE.md'), '');
  instructions(master, ['--write']);
  assert.equal(read(join(ws, 'CLAUDE.md')), block('master', text));
});

test('a block between two markers is replaced, and the text on both sides is kept', () => {
  const { ws, master } = workspace();
  const before = '# My notes\n\nKeep this line exactly as it is.\n\n';
  const after = '\n## After\n\nKeep this line too.\n';
  write(join(ws, 'CLAUDE.md'), `${before}${START}\nOLD INSTRUCTIONS FOR A SYSTEM THAT NO LONGER EXISTS\n${END}\n${after}`);
  const r = instructions(master, ['--write']);
  assert.equal(r.status, 0, r.stdout);
  assert.equal(r.json.claudeMd, 'updated');
  const text = read(join(master, 'intent', 'workspace.md'));
  const claude = read(join(ws, 'CLAUDE.md'));
  assert.equal(claude, `${before}${block('master', text)}${after}`);
  // the eval graders of setup-refreshes-instructions
  assert.doesNotMatch(claude, /OLD INSTRUCTIONS/);
  assert.doesNotMatch(claude, /hoshin:start[\s\S]*hoshin:start/);
  assert.match(claude, /<!-- hoshin:end -->\r?\n\r?\n## After\r?\n\r?\nKeep this line too\.\s*$/);
});

test('marker lines are matched after trimming whitespace, and kept as they are', () => {
  const { ws, master } = workspace();
  write(join(ws, 'CLAUDE.md'), `a\n  ${START}  \nold\n\t${END}\nb\n`);
  instructions(master, ['--write']);
  const text = read(join(master, 'intent', 'workspace.md'));
  assert.equal(read(join(ws, 'CLAUDE.md')), `a\n  ${START}  \n${generatedLine('master')}\n${text}\t${END}\nb\n`);
});

test('markers out of order, twice, or alone leave CLAUDE.md untouched and are listed', () => {
  const rows = [
    { text: `x\n${END}\ny\n${START}\n`, lines: [{ line: 2, text: END }, { line: 4, text: START }] },
    { text: `${START}\n${START}\n${END}\n`, lines: [{ line: 1, text: START }, { line: 2, text: START }, { line: 3, text: END }] },
    { text: `notes\n  ${START}\nmore\n`, lines: [{ line: 2, text: `  ${START}` }] },
  ];
  for (const r of rows) {
    const { ws, master } = workspace();
    write(join(ws, 'CLAUDE.md'), r.text);
    const out = instructions(master, ['--write']);
    assert.equal(out.status, 1, r.text);
    assert.equal(out.json.workspaceMd, 'written');
    assert.equal(out.json.claudeMd, 'bad-markers');
    assert.deepEqual(out.json.markerLines, r.lines);
    assert.equal(out.json.problems.length, 1);
    assert.match(out.json.problems[0], /CLAUDE\.md/);
    assert.equal(read(join(ws, 'CLAUDE.md')), r.text, 'it changed CLAUDE.md');
    const checked = instructions(master);
    assert.equal(checked.json.claudeMd, 'bad-markers');
    assert.equal(checked.status, 1);
  }
});

test('a second write changes nothing', () => {
  const { ws, master } = workspace();
  write(join(ws, 'CLAUDE.md'), '# notes\n');
  instructions(master, ['--write']);
  const before = [read(join(master, 'intent', 'workspace.md')), read(join(ws, 'CLAUDE.md'))];
  const r = instructions(master, ['--write']);
  assert.equal(r.status, 0);
  assert.deepEqual(r.json, { workspaceMd: 'current', claudeMd: 'current', markerLines: [{ line: 3, text: START }, { line: before[1].split('\n').indexOf(END) + 1, text: END }], problems: [] });
  assert.deepEqual([read(join(master, 'intent', 'workspace.md')), read(join(ws, 'CLAUDE.md'))], before);
});

test('check mode: missing, current, stale, and nothing written', () => {
  const { ws, master } = workspace();
  let r = instructions(master);
  assert.equal(r.status, 1);
  assert.equal(r.json.workspaceMd, 'missing');
  assert.equal(r.json.claudeMd, 'missing');
  assert.deepEqual(r.json.problems, ['This workspace has no workspace instructions yet; run the hoshin setup skill with `--instructions`.']);
  assert.equal(existsSync(join(master, 'intent', 'workspace.md')), false);
  assert.equal(existsSync(join(ws, 'CLAUDE.md')), false);

  instructions(master, ['--write']);
  r = instructions(master);
  assert.equal(r.status, 0, r.stdout);
  assert.deepEqual([r.json.workspaceMd, r.json.claudeMd, r.json.problems], ['current', 'current', []]);

  // line endings, blank lines at either end and trailing whitespace in the block do not count
  const claude = read(join(ws, 'CLAUDE.md'));
  write(join(ws, 'CLAUDE.md'), claude.replace(`${generatedLine('master')}\n`, `${generatedLine('master')}\n\n`).replaceAll('\n', '  \r\n'));
  assert.equal(instructions(master).json.claudeMd, 'current');

  write(join(ws, 'CLAUDE.md'), claude.replace('## Systems', '## Old systems'));
  r = instructions(master);
  assert.equal(r.status, 1);
  assert.equal(r.json.claudeMd, 'stale');
  assert.deepEqual(r.json.problems, ['The workspace instructions on this machine are missing or out of date; run the hoshin setup skill with `--instructions`.']);

  write(join(ws, 'CLAUDE.md'), '# notes only\n');
  assert.equal(instructions(master).json.claudeMd, 'missing');

  write(join(ws, 'CLAUDE.md'), claude);
  writeFileSync(join(master, '.hoshin.json'), JSON.stringify({ version: 1, systems: { demo: { repos: ['app'] }, other: { repos: ['app'] } } }));
  r = instructions(master);
  assert.equal(r.status, 1);
  assert.equal(r.json.workspaceMd, 'stale');
  assert.equal(r.json.claudeMd, 'current', 'the block is compared with intent/workspace.md as it is');
  assert.equal(r.json.problems.length, 1);
});

test('the home folder: CLAUDE.md is left alone unless --allow-home, and check mode does not count it', () => {
  const { ws, master } = workspace();
  const home = { HOME: ws, USERPROFILE: ws };
  let r = instructions(master, ['--write'], home);
  assert.equal(r.status, 1);
  assert.equal(r.json.workspaceMd, 'written');
  assert.equal(r.json.claudeMd, 'home-folder');
  assert.equal(r.json.problems.length, 1);
  assert.match(r.json.problems[0], /home folder/);
  assert.equal(existsSync(join(ws, 'CLAUDE.md')), false);

  r = instructions(master, [], home);
  assert.equal(r.status, 0, r.stdout);
  assert.deepEqual([r.json.workspaceMd, r.json.claudeMd, r.json.problems], ['current', 'home-folder', []]);

  r = instructions(master, ['--write', '--allow-home'], home);
  assert.equal(r.status, 0, r.stdout);
  assert.equal(r.json.claudeMd, 'created');
  assert.equal(instructions(master, ['--allow-home'], home).json.claudeMd, 'current');
});

test('it cannot run without a master or with a marker that lists no system', () => {
  const { ws, master } = workspace();
  const elsewhere = join(ws, 'app');
  writeFileSync(join(master, '.hoshin.json'), JSON.stringify({ version: 1, systems: {} }));
  let r = instructions(master, ['--write']);
  assert.equal(r.status, 2);
  assert.match(r.stderr, /no system/);
  renameSync(join(master, '.hoshin.json'), join(master, 'gone.json'));
  r = instructions(elsewhere);
  assert.equal(r.status, 2);
  assert.match(r.stderr, /No master repository found/);
  assert.equal(run(master, ['instructions']).status, 2, 'it ran without --json');
});
