// The workspace instructions in the single-repo layout: the block lives in the repository's own root CLAUDE.md,
// next to `intent/workspace.md`, and the workspace folder (the repository's parent) is never written.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { run } from './helpers/workspace.mjs';
import { singleRepo } from './helpers/single-repo.mjs';

const START = '<!-- hoshin:start -->';
const END = '<!-- hoshin:end -->';
const instructions = (cwd, more = []) => run(cwd, ['instructions', '--json', ...more]);
const read = (path) => readFileSync(path, 'utf8');

test('--write creates the block in the root CLAUDE.md and never writes the parent folder', () => {
  const s = singleRepo();
  const r = instructions(s.repo, ['--write']);
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.deepEqual(r.json, { workspaceMd: 'written', claudeMd: 'created', markerLines: [], problems: [] });
  const text = read(join(s.repo, 'intent', 'workspace.md'));
  assert.equal(read(join(s.repo, 'CLAUDE.md')), `${START}\n<!-- generated by hoshin setup from intent/workspace.md; edit outside this block -->\n${text}${END}\n`);
  assert.equal(existsSync(join(s.workspace, 'CLAUDE.md')), false);
});

test('the text names the layout, the system, each app with its folder, context file and staleness command', () => {
  const s = singleRepo();
  instructions(s.repo, ['--write']);
  const text = read(join(s.repo, 'intent', 'workspace.md'));
  assert.match(text, /single-repo layout/);
  assert.match(text, /one system, `demo`/);
  assert.match(text, /^\| api \| `apps\/api` \| `intent\/demo\/context\/api\.md` \| `git rev-list --count <source_commit>\.\.HEAD -- apps\/api ":\(exclude\)intent" ":\(exclude\)\.hoshin\.json"` \|$/m);
  assert.match(text, /^\| web \| `apps\/web` \| `intent\/demo\/context\/web\.md` \|/m);
  assert.match(text, /`intent\/demo\/policies\.md`/);
  assert.match(text, /stays in one app/);
  assert.doesNotMatch(text, /<master>|<app folder>|<system>|\r/);
  assert.ok(text.endsWith('.\n') && !text.endsWith('\n\n'));
});

test('text outside the markers is kept, and a second run reports current', () => {
  const s = singleRepo();
  const notes = '# Mono\n\nKeep this line.\n';
  writeFileSync(join(s.repo, 'CLAUDE.md'), notes);
  let r = instructions(s.repo, ['--write']);
  assert.equal(r.json.claudeMd, 'updated');
  const claude = read(join(s.repo, 'CLAUDE.md'));
  assert.ok(claude.startsWith(`${notes}\n${START}\n`));
  r = instructions(s.repo, ['--write']);
  assert.deepEqual(r.json, { workspaceMd: 'current', claudeMd: 'current', markerLines: r.json.markerLines, problems: [] });
  assert.equal(read(join(s.repo, 'CLAUDE.md')), claude);
  r = instructions(s.repo);
  assert.equal(r.status, 0, r.stdout);
  assert.equal(r.json.claudeMd, 'current');
});

test('a check reports missing, then stale after the marker changes', () => {
  const s = singleRepo();
  let r = instructions(s.repo);
  assert.equal(r.status, 1);
  assert.equal(r.json.workspaceMd, 'missing');
  assert.equal(r.json.claudeMd, 'missing');
  instructions(s.repo, ['--write']);
  const marker = JSON.parse(read(join(s.repo, '.hoshin.json')));
  marker.systems.demo.apps.docs = 'docs';
  writeFileSync(join(s.repo, '.hoshin.json'), JSON.stringify(marker));
  r = instructions(s.repo);
  assert.equal(r.status, 1);
  assert.equal(r.json.workspaceMd, 'stale');
});

test('bad markers leave the file untouched, and the home folder rule does not apply', () => {
  const s = singleRepo();
  writeFileSync(join(s.repo, 'CLAUDE.md'), `${START}\nno end\n`);
  const r = instructions(s.repo, ['--write']);
  assert.equal(r.json.claudeMd, 'bad-markers');
  assert.equal(read(join(s.repo, 'CLAUDE.md')), `${START}\nno end\n`);
  const h = singleRepo();
  const w = run(h.repo, ['instructions', '--json', '--write'], { HOME: h.repo, USERPROFILE: h.repo });
  assert.notEqual(w.json.claudeMd, 'home-folder');
});

test('commit --kind instructions commits CLAUDE.md with intent/workspace.md', () => {
  const s = singleRepo();
  instructions(s.repo, ['--write']);
  const r = run(s.repo, ['commit', '--json', '--kind', 'instructions', '--', 'intent/workspace.md', 'CLAUDE.md']);
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.equal(s.git('status', '--porcelain'), '');
  assert.deepEqual(s.git('show', '--name-only', '--format=', 'HEAD').split('\n').sort(), ['CLAUDE.md', 'intent/workspace.md']);
});

test('from a copy the copy\'s own CLAUDE.md is written', () => {
  const s = singleRepo();
  const copy = join(s.root, 'copies', 'x');
  s.git('worktree', 'add', '-q', '-b', 'change/x', copy);
  const r = instructions(copy, ['--write']);
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.ok(existsSync(join(copy, 'CLAUDE.md')));
  assert.equal(existsSync(join(s.repo, 'CLAUDE.md')), false);
  assert.equal(existsSync(join(s.workspace, 'CLAUDE.md')), false);
});
